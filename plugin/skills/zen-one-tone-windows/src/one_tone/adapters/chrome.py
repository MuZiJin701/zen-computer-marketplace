class _LiveProcessBlockedError(RuntimeError):
    """Raised when chrome.exe is running or process status cannot be verified."""


class _WriteTargetRedirectedError(OSError):
    """Raised when the Chrome Preferences target is redirected or changed concurrently."""


def seed_color_to_skcolor_int(seed_color: str) -> int:
    """Encode a #RRGGBB Seed Color into Chrome's signed 32-bit ARGB SkColor integer."""
    red, green, blue = parse_hex_color(seed_color)
    return ((0xFF << 24) | (red << 16) | (green << 8) | blue) - 0x100000000


def _is_strict_int(value: Any) -> bool:
    return isinstance(value, int) and not isinstance(value, bool)


def _generated_values(plan: Plan) -> dict[str, Any]:
    return {
        "browser.theme.color_scheme2": CHROME_COLOR_SCHEME_SYSTEM,
        "browser.theme.color_variant2": CHROME_COLOR_VARIANT_TONAL_SPOT,
        "browser.theme.follows_system_colors": False,
        "browser.theme.user_color2": seed_color_to_skcolor_int(plan.seed_color),
        "extensions.theme.id": CHROME_USER_COLOR_THEME_ID,
    }


def _abs_unexpanded_path(path: Path) -> Path:
    return Path(os.path.abspath(str(path.expanduser())))


def _norm_path(path: str | Path) -> str:
    return os.path.normcase(os.path.normpath(str(path)))


_create_kernel32 = create_kernel32


def probe_chrome_process() -> tuple[str, str]:
    """Probe whether chrome.exe is running on Windows (fail-closed -> 'unknown')."""
    if sys.platform != "win32":
        return "stopped", "non-windows host"
    return probe_windows_process("chrome.exe", kernel32_factory=_create_kernel32)


def _is_safe_profile_dirname(name: Any) -> bool:
    if not isinstance(name, str) or not name or name in {".", ".."} or name.strip() != name:
        return False
    return not any(sep in name for sep in ("/", "\\", ":", "\x00")) and Path(name).name == name and not Path(name).is_absolute()


def _validate_preferences_payload(payload: Any) -> tuple[bool, str]:
    if not isinstance(payload, dict):
        return False, "Chrome Preferences root must be a JSON object"
    for top_key in ("browser", "extensions", "autogenerated", "ntp"):
        section = payload.get(top_key)
        if section is not None:
            if not isinstance(section, dict):
                return False, f"Chrome Preferences '{top_key}' must be a JSON object"
            if top_key != "ntp" and section.get("theme") is not None and not isinstance(section.get("theme"), dict):
                return False, f"Chrome Preferences '{top_key}.theme' must be a JSON object"
    return True, "ok"


def _read_and_validate_preferences(path: Path) -> tuple[bool, bytes, dict[str, Any] | None, str]:
    ok_path, resolved, path_err = verify_unredirected_path(path, "Chrome Preferences", require_file=True)
    if not ok_path or resolved is None:
        return False, b"", None, path_err
    try:
        raw_bytes = resolved.read_bytes()
        payload = json.loads(raw_bytes.decode("utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
        return False, b"", None, f"Chrome Preferences unreadable or invalid JSON: {error}"
    ok_schema, schema_err = _validate_preferences_payload(payload)
    return (True, raw_bytes, payload, "ok") if ok_schema else (False, raw_bytes, None, schema_err)


def _has_chrome_sync_indicators(payload: Mapping[str, Any]) -> bool:
    browser = payload.get("browser")
    browser_theme = browser.get("theme") if isinstance(browser, Mapping) else None
    return (isinstance(browser_theme, Mapping) and "saved_local_theme" in browser_theme) or isinstance(payload.get("account_values"), Mapping)


def _get_nested(payload: Mapping[str, Any], parts: tuple[str, ...]) -> tuple[bool, Any]:
    current: Any = payload
    for part in parts[:-1]:
        if not isinstance(current, Mapping):
            return False, None
        current = current.get(part)
    if not isinstance(current, Mapping) or parts[-1] not in current:
        return False, None
    return True, current[parts[-1]]


def _set_nested(payload: dict[str, Any], parts: tuple[str, ...], value: Any) -> None:
    current = payload
    for part in parts[:-1]:
        nxt = current.get(part)
        if not isinstance(nxt, dict):
            nxt = {}
            current[part] = nxt
        current = nxt
    current[parts[-1]] = value


def _pop_nested(payload: dict[str, Any], parts: tuple[str, ...]) -> None:
    current: Any = payload
    for part in parts[:-1]:
        if not isinstance(current, dict):
            return
        current = current.get(part)
    if isinstance(current, dict):
        current.pop(parts[-1], None)


def _read_local_state_last_used(user_data_dir: Path) -> str | None:
    local_state_path = user_data_dir / "Local State"
    if not local_state_path.is_file() or local_state_path.is_symlink():
        return None
    try:
        payload = json.loads(local_state_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError):
        return None
    profile_section = payload.get("profile") if isinstance(payload, dict) else None
    last_used = profile_section.get("last_used") if isinstance(profile_section, dict) else None
    return last_used if _is_safe_profile_dirname(last_used) else None


def discover_chrome_instance(
    localappdata: Path | None = None,
    *,
    explicit_preferences: Path | None = None,
) -> dict[str, Any]:
    """Discover and validate the single active Google Chrome desktop Profile."""
    env_override = os.environ.get("ONE_TONE_CHROME_PREFERENCES")
    if explicit_preferences is not None or env_override:
        raw_path = explicit_preferences if explicit_preferences is not None else Path(env_override)  # type: ignore[arg-type]
        candidate = _abs_unexpanded_path(raw_path)
        source, profile_name = ("explicit" if explicit_preferences is not None else "env"), (candidate.parent.name or "Default")
    else:
        base = localappdata if localappdata is not None else Path(os.environ.get("LOCALAPPDATA", Path.home() / "AppData/Local"))
        user_data = _abs_unexpanded_path(base / "Google" / "Chrome" / "User Data")
        if not user_data.is_dir():
            return {"status": "skipped", "reason": f"Google Chrome User Data directory not found: {user_data}"}
        last_used = _read_local_state_last_used(user_data)
        last_used_pref = (user_data / last_used / "Preferences") if last_used is not None else None
        if last_used is not None and last_used_pref is not None and (last_used_pref.exists() or last_used_pref.is_symlink()):
            candidate, profile_name, source = _abs_unexpanded_path(last_used_pref), last_used, "local_state"
        else:
            candidate, profile_name, source = _abs_unexpanded_path(user_data / "Default" / "Preferences"), "Default", "default"

    ok, _, _, reason = _read_and_validate_preferences(candidate)
    if not ok:
        return {"status": "skipped", "reason": reason}
    return {"status": "ok", "preferences_path": str(candidate), "profile": profile_name, "source": source}


def _atomic_write_preferences(target_path: Path, payload: Mapping[str, Any], *, pre_replace_check: Callable[[], None]) -> None:
    serialized = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    temporary = target_path.with_name(f".{target_path.name}.{uuid.uuid4().hex}.tmp")
    try:
        with temporary.open("w", encoding="utf-8", newline="") as handle:
            handle.write(serialized)
            handle.flush()
            os.fsync(handle.fileno())
        pre_replace_check()
        os.replace(temporary, target_path)
    finally:
        try:
            temporary.unlink()
        except FileNotFoundError:
            pass


class ChromeAdapter:
    target = "chrome"

    def __init__(
        self,
        target_instance: Mapping[str, Any] | None = None,
        *,
        preferences_path: Path | None = None,
        localappdata: Path | None = None,
        process_probe: Callable[[], tuple[str, str]] | None = None,
        process_closer: Callable[[], tuple[bool, str]] | None = None,
    ) -> None:
        self._explicit_preferences = preferences_path
        self._localappdata = localappdata
        self._process_probe = process_probe or probe_chrome_process
        if process_closer is not None:
            self._process_closer: Callable[[], tuple[bool, str]] | None = process_closer
        elif process_probe is None:
            self._process_closer = lambda: close_windows_process("chrome.exe", process_probe=self._process_probe)
        else:
            self._process_closer = None
        self._frozen_instance: dict[str, Any] | None = dict(target_instance) if target_instance is not None else None
        self._cached_instance: dict[str, Any] | None = None
        self.preferences_path: Path | None = None
        if self._frozen_instance is not None:
            raw_path = self._frozen_instance.get("preferences_path")
            if self._frozen_instance.get("status") == "ok" and isinstance(raw_path, str) and raw_path and Path(raw_path).is_absolute():
                self.preferences_path = Path(raw_path)
            elif self._frozen_instance.get("status") == "ok":
                self._frozen_instance = {"status": "skipped", "reason": f"Invalid frozen Chrome preferences_path: {raw_path!r}"}
        elif preferences_path is not None:
            self.preferences_path = _abs_unexpanded_path(preferences_path)

    def _fail(self, message: str, *, changed: bool = False, aborted_before_write: bool = False, metadata: dict[str, Any] | None = None) -> AdapterResult:
        meta = dict(metadata or {})
        if aborted_before_write:
            meta["aborted_before_write"] = True
        return AdapterResult(self.target, "failed", changed, False, message, version=CHROME_PREFERENCES_SCHEMA_V1, metadata=meta)

    def _skip(self, message: str, *, instance: Mapping[str, Any] | None = None) -> AdapterResult:
        if instance is None:
            return AdapterResult(self.target, "skipped", False, False, message)
        return AdapterResult(self.target, "skipped", False, False, message, version=CHROME_PREFERENCES_SCHEMA_V1, metadata={"target_instance": dict(instance)})

    def _resolve_instance(self) -> dict[str, Any]:
        if self._frozen_instance is not None:
            return dict(self._frozen_instance)
        if self._cached_instance is None:
            self._cached_instance = discover_chrome_instance(self._localappdata, explicit_preferences=self._explicit_preferences)
            if self._cached_instance.get("status") == "ok" and self._cached_instance.get("preferences_path"):
                self.preferences_path = Path(str(self._cached_instance["preferences_path"]))
        return dict(self._cached_instance)

    def target_instance(self) -> dict[str, Any]:
        return self._resolve_instance()

    def _is_process_blocked(self) -> tuple[bool, str]:
        try:
            status, detail = self._process_probe()
        except Exception as error:
            return True, f"Unable to verify whether Chrome is running ({error}); refusing to write Preferences"
        if status != "stopped":
            suffix = f" ({detail})" if detail else ""
            return True, f"Chrome is running or process status could not be verified{suffix}; close Chrome completely and retry"
        return False, ""

    def _ensure_process_stopped(self) -> tuple[bool, str, bool]:
        try:
            status, detail = self._process_probe()
        except Exception as error:
            return True, f"Unable to verify whether Chrome is running ({error}); refusing to write Preferences", False
        if status == "stopped":
            return False, "", False
        if status == "running" and self._process_closer is not None:
            try:
                closed, close_detail = self._process_closer()
            except Exception as error:
                return True, f"Unable to close running Chrome ({error}); refusing to write Preferences", False
            try:
                status, detail = self._process_probe()
            except Exception as error:
                return True, f"Unable to verify Chrome exit after shutdown ({error}); refusing to write Preferences", False
            if closed and status == "stopped":
                return False, "", True
            suffix = f" ({close_detail or detail})" if (close_detail or detail) else ""
            return True, f"Chrome remained running or could not be verified after shutdown attempt{suffix}; close Chrome completely and retry", False
        suffix = f" ({detail})" if detail else ""
        return True, f"Chrome is running or process status could not be verified{suffix}; close Chrome completely and retry", False

    def _pre_replace_guard(self, frozen_path: Path, expected_raw_bytes: bytes) -> Callable[[], None]:
        def _check() -> None:
            blocked, reason = self._is_process_blocked()
            if blocked:
                raise _LiveProcessBlockedError(reason)
            ok_path, resolved, path_err = verify_unredirected_path(frozen_path, "Chrome Preferences", require_file=True)
            if not ok_path or resolved is None:
                raise _WriteTargetRedirectedError(path_err)
            try:
                current_bytes = resolved.read_bytes()
            except OSError as error:
                raise _WriteTargetRedirectedError(f"Chrome Preferences unavailable before replace: {error}") from error
            if current_bytes != expected_raw_bytes:
                raise _WriteTargetRedirectedError(f"Chrome Preferences changed concurrently before atomic replace: {frozen_path}")

        return _check

    def _metadata(self, plan: Plan | None = None, status: str = "supported", *, target_instance: dict[str, Any] | None = None, sync_caveat: bool = False) -> dict[str, Any]:
        statuses = {name: status if cap == "supported" else cap for name, cap in field_capabilities(self.target).items()}
        values = _generated_values(plan) if plan is not None else {}
        return {
            "field_capabilities": statuses,
            "generated_values": values,
            "field_inventory": inventory_report(self.target, statuses, values),
            "field_groups": inventory_groups(self.target, statuses, values),
            "target_instance": dict(target_instance) if target_instance is not None else self.target_instance(),
            "sync_caveat": sync_caveat,
            "rendering_verification": "untested",
        }

    def _load_checked(self) -> tuple[bool, Path | None, bytes, dict[str, Any] | None, dict[str, Any], str]:
        instance = self._resolve_instance()
        if instance.get("status") != "ok" or not instance.get("preferences_path"):
            return False, None, b"", None, instance, str(instance.get("reason") or "Google Chrome Preferences not found")
        path = Path(str(instance["preferences_path"]))
        ok, raw_bytes, payload, reason = _read_and_validate_preferences(path)
        return (True, path, raw_bytes, payload, instance, "ok") if ok and payload is not None else (False, path, raw_bytes, None, instance, reason)

    def detect(self) -> AdapterResult:
        ok, path, _, payload, instance, reason = self._load_checked()
        if not ok or path is None or payload is None:
            return self._skip(reason)
        sync_caveat = _has_chrome_sync_indicators(payload)
        msg = f"verified Google Chrome ({instance.get('profile', path.parent.name)}) Preferences ({path}); Material 3 kTonalSpot follows system Light/Dark; rendering untested"
        if sync_caveat:
            msg += "; Chrome Sync detected (reset to default theme once in Customize Chrome if an older cloud theme overrides changes)"
        return AdapterResult(self.target, "ok", False, True, msg, version=CHROME_PREFERENCES_SCHEMA_V1, metadata=self._metadata(target_instance=instance, sync_caveat=sync_caveat))

    def snapshot(self, backup_dir: Path) -> AdapterResult:
        ok, path, raw_bytes, payload, instance, reason = self._load_checked()
        if not ok or path is None or payload is None:
            return self._skip(reason)
        blocked, block_reason, was_closed = self._ensure_process_stopped()
        if blocked:
            return self._skip(block_reason, instance=instance)
        if was_closed:
            ok, path, raw_bytes, payload, instance, reason = self._load_checked()
            if not ok or path is None or payload is None:
                return self._skip(reason)
        try:
            backup_dir.mkdir(parents=True, exist_ok=True)
            (backup_dir / "chrome-preferences.json").write_bytes(raw_bytes)
            containers = {
                "browser": isinstance(payload.get("browser"), dict),
                "browser.theme": isinstance((payload.get("browser") or {}).get("theme"), dict),
                "extensions": isinstance(payload.get("extensions"), dict),
                "extensions.theme": isinstance((payload.get("extensions") or {}).get("theme"), dict),
                "ntp": isinstance(payload.get("ntp"), dict),
            }
            entries = {
                dotted: ({"existed": True, "value": copy.deepcopy(val)} if existed else {"existed": False})
                for parts, dotted in _MANAGED_KEYS
                for existed, val in (_get_nested(payload, parts),)
            }
            state_payload = {
                "schema": CHROME_PREFERENCES_SCHEMA_V1,
                "preferences_path": str(path),
                "profile": str(instance.get("profile") or path.parent.name),
                "snapshot_sha256": hashlib.sha256(raw_bytes).hexdigest(),
                "containers": containers,
                "entries": entries,
            }
            atomic_write_text(backup_dir / "chrome-state.json", json.dumps(state_payload, ensure_ascii=False, sort_keys=True))
            return AdapterResult(self.target, "ok", False, True, f"Chrome {state_payload['profile']} Preferences snapshot saved", version=CHROME_PREFERENCES_SCHEMA_V1, metadata={"target_instance": instance})
        except OSError as error:
            return self._fail(f"Chrome snapshot failed: {error}")

    @staticmethod
    def _read_snapshot_guard(backup_dir: Path) -> tuple[bool, tuple[str, str] | None, str]:
        try:
            state = json.loads((backup_dir / "chrome-state.json").read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
            return False, None, f"Chrome snapshot state unreadable: {error}"
        snap_path, snap_sha = state.get("preferences_path"), state.get("snapshot_sha256")
        if not isinstance(snap_path, str) or not snap_path or not Path(snap_path).is_absolute():
            return False, None, f"Chrome snapshot preferences_path is invalid: {snap_path!r}"
        if not isinstance(snap_sha, str) or len(snap_sha) != 64:
            return False, None, "Chrome snapshot state is missing snapshot_sha256"
        return True, (_norm_path(snap_path), snap_sha), "ok"

    def apply_with_backup(self, plan: Plan, backup_dir: Path) -> AdapterResult:
        return self.apply(plan, backup_dir=backup_dir)

    def apply(self, plan: Plan, *, backup_dir: Path | None = None) -> AdapterResult:
        expected_snapshot: tuple[str, str] | None = None
        if backup_dir is not None:
            ok_guard, expected_snapshot, guard_err = self._read_snapshot_guard(backup_dir)
            if not ok_guard or expected_snapshot is None:
                return self._fail(f"Chrome apply aborted before write: {guard_err}", aborted_before_write=True)
        ok, path, raw_bytes, payload, instance, reason = self._load_checked()
        if not ok or path is None or payload is None:
            return self._fail(f"Chrome apply aborted before write (Preferences changed or invalid since snapshot): {reason}", aborted_before_write=True) if expected_snapshot is not None else self._skip(reason)

        blocked, block_reason, was_closed = self._ensure_process_stopped()
        if blocked:
            return self._skip(block_reason, instance=instance)
        if was_closed:
            ok, path, raw_bytes, payload, instance, reason = self._load_checked()
            if not ok or path is None or payload is None:
                return self._fail(f"Chrome apply aborted before write (Preferences changed or invalid after closing Chrome): {reason}", aborted_before_write=True) if expected_snapshot is not None else self._skip(reason)
        if expected_snapshot is not None and (_norm_path(path), hashlib.sha256(raw_bytes).hexdigest()) != expected_snapshot:
            return self._fail(f"Chrome Preferences changed since snapshot: {path}", aborted_before_write=True)

        replaced = False
        try:
            updated = copy.deepcopy(payload)
            values = _generated_values(plan)
            for parts, dotted in _MANAGED_KEYS:
                _pop_nested(updated, parts) if dotted in _REMOVED_KEYS else _set_nested(updated, parts, values[dotted])
            _atomic_write_preferences(path, updated, pre_replace_check=self._pre_replace_guard(path, raw_bytes))
            replaced = True
            sync_caveat = _has_chrome_sync_indicators(updated)
            msg = f"Google Chrome ({instance.get('profile', path.parent.name)}) native Material 3 kTonalSpot theme applied (follows system Light/Dark)"
            if sync_caveat:
                msg += "; Chrome Sync detected: if a previously UI-selected cloud theme overrides this color on launch, reset to the default Chrome theme once in Customize Chrome or turn off theme sync"
            return AdapterResult(self.target, "ok", True, False, msg, requires_user_action=False, version=CHROME_PREFERENCES_SCHEMA_V1, metadata=self._metadata(plan, "applied", target_instance=instance, sync_caveat=sync_caveat))
        except _LiveProcessBlockedError as error:
            return self._skip(str(error), instance=instance)
        except (_WriteTargetRedirectedError, OSError, UnicodeError, json.JSONDecodeError) as error:
            return self._fail(f"Chrome apply failed after write: {error}" if replaced else f"Chrome apply failed: {error}", changed=replaced, aborted_before_write=not replaced)

    def verify(self, plan: Plan) -> AdapterResult:
        instance = self._resolve_instance()
        if instance.get("status") != "ok" or not instance.get("preferences_path"):
            return self._skip(str(instance.get("reason") or "Google Chrome target not found"))
        path = Path(str(instance["preferences_path"]))
        ok, _, payload, reason = _read_and_validate_preferences(path)
        if not ok or payload is None:
            return self._fail(f"Chrome verify failed: {reason}", metadata=self._metadata(plan, "failed", target_instance={"status": "skipped", "reason": reason}))

        expected = _generated_values(plan)
        mismatches: list[str] = []
        for parts, dotted in _MANAGED_KEYS:
            existed, actual = _get_nested(payload, parts)
            if dotted in _REMOVED_KEYS:
                if existed:
                    mismatches.append(dotted)
            elif not existed or (
                (not _is_strict_int(actual) or actual != expected[dotted]) if dotted in _STRICT_INT_KEYS
                else (actual is not False) if dotted == "browser.theme.follows_system_colors"
                else (actual != expected[dotted])
            ):
                mismatches.append(dotted)

        verified, sync_caveat = not mismatches, _has_chrome_sync_indicators(payload)
        profile = instance.get("profile", path.parent.name)
        msg = f"Google Chrome ({profile}) native Preferences verified; rendering untested" if verified else f"Google Chrome Preferences mismatch ({', '.join(mismatches[:5])}); rendering untested"
        if verified and sync_caveat:
            msg += "; Chrome Sync detected"
        return AdapterResult(self.target, "ok" if verified else "failed", False, verified, msg, requires_user_action=False, version=CHROME_PREFERENCES_SCHEMA_V1, metadata=self._metadata(plan, "verified" if verified else "failed", target_instance=instance, sync_caveat=sync_caveat))

    def _load_rollback_state(self, backup_dir: Path, metadata: Mapping[str, Any] | None) -> tuple[dict[str, Any] | None, Path | None, str]:
        state_path = backup_dir / "chrome-state.json"
        if not state_path.is_file():
            return None, None, "Chrome backup state not found (legacy MV3 extension snapshots are not supported)"
        try:
            state = json.loads(state_path.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
            return None, None, f"Chrome backup state unreadable: {error}"
        if not isinstance(state, dict) or state.get("schema") != CHROME_PREFERENCES_SCHEMA_V1 or not isinstance(state.get("containers"), dict) or not isinstance(state.get("entries"), dict):
            return None, None, "Chrome backup state is invalid"
        raw_snap = state.get("preferences_path")
        if not isinstance(raw_snap, str) or not raw_snap or not Path(raw_snap).is_absolute():
            return None, None, f"Chrome snapshot preferences_path must be absolute: {raw_snap!r}"
        frozen_path = Path(raw_snap)
        ok_path, resolved, path_err = verify_unredirected_path(frozen_path, "Chrome Preferences", require_file=True)
        if not ok_path or resolved is None:
            return None, None, f"Chrome rollback aborted: {path_err}"
        expected_norm = _norm_path(frozen_path)
        if self.preferences_path is not None:
            if not self.preferences_path.is_absolute():
                return None, None, f"Chrome adapter preferences_path must be absolute for rollback: {self.preferences_path}"
            if _norm_path(self.preferences_path) != expected_norm:
                return None, None, f"Chrome rollback aborted: adapter path {self.preferences_path} does not match snapshot path {frozen_path}"
        if isinstance(metadata, Mapping) and isinstance(metadata.get("target_instance"), Mapping):
            meta_path = metadata["target_instance"].get("preferences_path")
            if isinstance(meta_path, str) and meta_path and Path(meta_path).is_absolute() and _norm_path(meta_path) != expected_norm:
                return None, None, f"Chrome rollback aborted: transaction metadata path {meta_path} does not match snapshot path {frozen_path}"
        for _, dotted in _MANAGED_KEYS:
            key_state = state["entries"].get(dotted)
            if key_state is None and dotted not in _CORE_MANAGED_KEYS:
                continue
            if not isinstance(key_state, dict):
                return None, None, "Chrome backup state is missing managed key snapshots"
            if key_state.get("existed") and "value" not in key_state:
                return None, None, f"Chrome backup state missing value for {dotted}"
        return state, frozen_path, ""

    def rollback(self, backup_dir: Path, metadata: Mapping[str, Any] | None = None) -> AdapterResult:
        blocked, block_reason, _ = self._ensure_process_stopped()
        if blocked:
            return self._fail(block_reason)
        state, frozen_path, state_err = self._load_rollback_state(backup_dir, metadata)
        if state is None or frozen_path is None:
            return self._fail(state_err)
        ok_load, raw_bytes, current_payload, load_err = _read_and_validate_preferences(frozen_path)
        if not ok_load or current_payload is None:
            return self._fail(f"Chrome rollback aborted (Preferences invalid): {load_err}")

        entries_state, containers_state, replaced = state["entries"], state["containers"], False
        try:
            restored_payload = copy.deepcopy(current_payload)
            for parts, dotted in _MANAGED_KEYS:
                if dotted not in entries_state:
                    continue
                key_state = entries_state[dotted]
                _set_nested(restored_payload, parts, copy.deepcopy(key_state["value"])) if key_state.get("existed") else _pop_nested(restored_payload, parts)
            for container_key, parts in _CONTAINER_CLEANUP_ORDER:
                if containers_state.get(container_key) is False:
                    existed, val = _get_nested(restored_payload, parts)
                    if existed and isinstance(val, dict) and not val:
                        _pop_nested(restored_payload, parts)

            _atomic_write_preferences(frozen_path, restored_payload, pre_replace_check=self._pre_replace_guard(frozen_path, raw_bytes))
            replaced = True
            ok_verify, _, verify_payload, _ = _read_and_validate_preferences(frozen_path)
            restored = ok_verify and verify_payload is not None and all(
                (existed and actual == entries_state[dotted]["value"] and type(actual) is type(entries_state[dotted]["value"]))
                if entries_state[dotted].get("existed") else (not existed)
                for parts, dotted in _MANAGED_KEYS
                if dotted in entries_state
                for existed, actual in (_get_nested(verify_payload, parts),)
            )
            return AdapterResult(self.target, "ok" if restored else "failed", True, restored, "Chrome managed Preferences restored (field-level)" if restored else "Chrome field-level restore verification failed", version=CHROME_PREFERENCES_SCHEMA_V1)
        except (_LiveProcessBlockedError, _WriteTargetRedirectedError) as error:
            return self._fail(str(error))
        except (OSError, UnicodeError, json.JSONDecodeError) as error:
            return self._fail(f"Chrome rollback failed after write: {error}" if replaced else f"Chrome rollback failed: {error}", changed=replaced)
